import { expect, test } from '@playwright/test';
import { fixturePdf } from '../../web/test-fixtures/pdf.js';
import { apiAs, closePool, registerCompany, signIn, watchErrors } from './support.js';

test.afterAll(closePool);
test('ATS, remoção de texto do CV, proposta de acordo com a pretensão e admissão com o acordo', async ({ page, context }) => {
  const owner = await registerCompany(); await signIn(context, owner.token); const errors = watchErrors(page);
  await page.goto('/recrutamento'); await page.getByRole('button', { name: 'Nova vaga', exact: true }).click();
  await page.getByLabel('Título', { exact: true }).fill('Analista com ATS');
  await page.getByText('ATS — requisitos e pesos profissionais (0)', { exact: true }).click();
  await page.getByRole('button', { name: 'Adicionar critério ATS', exact: true }).click();
  await page.getByLabel('Requisito 1', { exact: true }).fill('Excel');
  await page.getByRole('button', { name: 'Criar e publicar', exact: true }).click();
  await expect(page).toHaveURL(/\/recrutamento\/[^/?]+$/);
  const job = new URL(page.url()).pathname.split('/').pop()!;
  const candidate = await apiAs(owner.token, 'POST', `/v1/openings/${job}/candidates`, { name: 'Amélia Negociação', email: `amelia.${Date.now()}@e2e.kianda.test`, expectedSalary: 350000 }); expect(candidate.status).toBe(201);
  const id = candidate.body.id;
  await page.goto(`/recrutamento/candidatos/${id}`);
  const ats = page.getByRole('region', { name: 'ATS da candidatura', exact: true });
  await expect(ats).toContainText('100% por confirmar');
  await ats.getByText('Rever perfil profissional e analisar CV', { exact: true }).click();
  const pdf = Buffer.from(fixturePdf([[{ str: 'Trabalho com Excel e analise financeira.', transform: [10, 0, 0, 10, 40, 760], width: 300, height: 10 }]]));
  await ats.getByLabel('Ler CV para análise (PDF ou Word)', { exact: true }).setInputFiles({ name: 'cv-analista.pdf', mimeType: 'application/pdf', buffer: pdf });
  await expect(ats.getByLabel('Texto do CV para ATS', { exact: true })).toHaveValue(/Excel/);
  await ats.getByRole('button', { name: 'Guardar perfil e actualizar ATS', exact: true }).click();
  await expect(ats).toContainText('100% do peso com evidência encontrada');
  await ats.getByRole('button', { name: 'Remover texto de análise', exact: true }).click();
  await expect(ats).toContainText('100% por confirmar');
  await ats.getByLabel('Competências (separadas por vírgula)', { exact: true }).fill('Excel');
  await ats.getByRole('button', { name: 'Guardar perfil e actualizar ATS', exact: true }).click();
  await expect(ats).toContainText('100% do peso com evidência encontrada');
  await apiAs(owner.token, 'POST', `/v1/candidates/${id}/stage`, { stage: 'offer' }); await page.reload();
  const negotiation = page.getByRole('region', { name: 'Negociação salarial', exact: true });
  await negotiation.getByRole('button', { name: 'Preparar proposta salarial', exact: true }).click();
  await negotiation.getByLabel('Modalidade', { exact: true }).selectOption('accept_expected');
  await negotiation.getByRole('checkbox', { name: /Confirmei com o candidato/ }).check();
  await negotiation.getByLabel('Alimentação mensal (Kz)', { exact: true }).fill('30000');
  await negotiation.getByLabel('Transporte mensal (Kz)', { exact: true }).fill('20000');
  await negotiation.getByLabel('Início previsto', { exact: true }).fill('2026-12-01');
  await negotiation.getByRole('button', { name: 'Gerar proposta para revisão', exact: true }).click();
  await expect(negotiation.getByRole('link', { name: 'Ver proposta v1', exact: true })).toBeVisible();
  await negotiation.getByRole('link', { name: 'Ver proposta v1', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Proposta de acordo com a pretensão salarial', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Imprimir / PDF', exact: true })).toBeDisabled();
  await page.getByRole('link', { name: '← Voltar à candidatura', exact: true }).click();
  await negotiation.getByText('Registar resposta recebida do candidato', { exact: true }).click();
  await negotiation.getByLabel('Origem e conteúdo da resposta', { exact: true }).fill('Aceitação por email confirmada em reunião.');
  await negotiation.getByRole('button', { name: 'Registar resposta', exact: true }).click();
  await expect(negotiation).toContainText('Aceite pelo candidato');
  await page.getByRole('link', { name: 'Admitir…', exact: true }).click();
  await expect(page.getByLabel('Subsídio de alimentação (Kz)', { exact: true })).toHaveValue(/30[\s.]?000,00/);
  await expect(page.getByLabel('Subsídio de transporte (Kz)', { exact: true })).toHaveValue(/20[\s.]?000,00/);
  await expect(page.getByLabel('Data de início', { exact: true })).toHaveValue('2026-12-01');
  expect(errors).toEqual([]);
});

test('ATS e negociação salarial cabem no telefone', async ({ page, context }) => {
  const owner = await registerCompany(); await signIn(context, owner.token); await page.setViewportSize({ width: 390, height: 844 });
  const job = await apiAs(owner.token, 'POST', '/v1/openings', { title: 'Vaga mobile', status: 'open' });
  const person = await apiAs(owner.token, 'POST', `/v1/openings/${job.body.id}/candidates`, { name: 'Pessoa Mobile', email: 'mobile@example.test', expectedSalary: 250000 });
  await apiAs(owner.token, 'POST', `/v1/candidates/${person.body.id}/stage`, { stage: 'offer' });
  await page.goto(`/recrutamento/candidatos/${person.body.id}`);
  await page.getByRole('button', { name: 'Preparar proposta salarial', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Gerar proposta para revisão', exact: true })).toBeVisible();
  expect(await page.evaluate<number>('document.documentElement.scrollWidth - window.innerWidth')).toBeLessThanOrEqual(1);
});
