import { expect, test } from '@playwright/test';
import { fixturePdf } from '../../web/test-fixtures/pdf.js';
import { apiAs, closePool, registerCompany, signIn, watchErrors } from './support.js';

test.afterAll(closePool);
const cv = () => Buffer.from(fixturePdf([[{ str: 'Curriculo sintetico de Amelia', transform: [10, 0, 0, 10, 40, 760], width: 300, height: 10 }]]));

test('publicar uma vaga gera a ligação; candidatura anónima com CV entra no quadro e na ficha', async ({ page, context }) => {
  const errors = watchErrors(page), owner = await registerCompany(); await signIn(context, owner.token);
  await page.goto('/recrutamento'); await page.getByRole('button', { name: 'Nova vaga', exact: true }).click();
  await page.getByLabel('Título', { exact: true }).fill('Analista de controlo financeiro');
  await page.getByLabel('Local', { exact: true }).fill('Luanda');
  await page.getByLabel('Descrição', { exact: true }).fill('Analisar os resultados e acompanhar o orçamento.');
  await page.getByLabel('Requisitos', { exact: true }).fill('Licenciatura e experiência em finanças.');
  await page.getByRole('button', { name: 'Criar e publicar', exact: true }).click();
  await expect(page).toHaveURL(/\/recrutamento\/[^/?]+$/);
  const openingId = new URL(page.url()).pathname.split('/').pop()!;
  const link = page.getByLabel('Ligação da vaga', { exact: true });
  await expect(link).toHaveValue(new RegExp(`/carreiras/${owner.id}/vagas/${openingId}$`));
  const publicUrl = new URL(await link.inputValue(), 'http://localhost:3000').href;
  await page.getByRole('button', { name: 'Copiar ligação', exact: true }).click();
  await expect(page.getByRole('status')).toContainText(/Ligação copiada|Seleccione e copie/);
  await expect(page.getByRole('link', { name: 'Abrir portal de candidatura', exact: true })).toHaveAttribute('href', `/carreiras/${owner.id}/vagas/${openingId}`);
  await context.clearCookies(); await page.goto(publicUrl);
  await expect(page.getByRole('heading', { name: 'Analista de controlo financeiro', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: '← Todas as vagas', exact: true })).toBeVisible();
  await page.getByLabel('Nome completo', { exact: true }).fill('Amélia Portal');
  await page.getByLabel('Email', { exact: true }).fill(`amelia.${Date.now()}@e2e.kianda.test`);
  await page.getByLabel('Telefone', { exact: true }).fill('+244923000111');
  const picker = page.getByLabel('Currículo (CV)', { exact: true });
  await picker.setInputFiles({ name: 'curriculo-errado.pdf', mimeType: 'application/pdf', buffer: cv() });
  await page.getByRole('button', { name: 'Remover CV', exact: true }).click();
  await expect(picker).toHaveValue('');
  await picker.setInputFiles({ name: 'curriculo-amelia.pdf', mimeType: 'application/pdf', buffer: cv() });
  await page.getByText('Dados profissionais (opcional)', { exact: true }).click();
  await page.getByLabel('Função actual', { exact: true }).fill('Controller');
  await page.getByLabel('Anos de experiência', { exact: true }).fill('4');
  await page.getByLabel('Nível de formação', { exact: true }).selectOption('Licenciatura');
  await page.getByLabel('Autorizo o tratamento dos meus dados para este processo de recrutamento.', { exact: true }).check();
  await page.getByRole('button', { name: 'Enviar candidatura', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Candidatura recebida');
  await expect(page.getByRole('status')).toContainText(/K-[A-F0-9]{8}/);
  const reference = /K-[A-F0-9]{8}/.exec(await page.getByRole('status').innerText())![0];
  await signIn(context, owner.token); await page.goto(`/recrutamento/${openingId}`);
  await page.getByRole('link', { name: 'Amélia Portal', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Amélia Portal', exact: true })).toBeVisible();
  await expect(page.locator('body')).toContainText(reference);
  await expect(page.locator('body')).toContainText('4 ano(s)');
  await expect(page.getByRole('link', { name: 'curriculo-amelia.pdf', exact: true })).toBeVisible();
  await expect(page.locator('body')).toContainText('Candidatura recebida pelo portal público, com consentimento.');
  await page.getByRole('button', { name: 'Avançar para Triagem →', exact: true }).click();
  await expect(page.locator('body')).toContainText('Recebida → Triagem');
  expect(errors).toEqual([]);
});

test('suspender e fechar desactiva o link e impede o envio de um formulário já aberto', async ({ page }) => {
  const owner = await registerCompany();
  const created = await apiAs(owner.token, 'POST', '/v1/openings', { title: 'Vaga temporária', status: 'open', isPublic: true }); expect(created.status).toBe(201);
  const path = created.body.publicPath;
  await page.goto(path);
  await page.getByLabel('Nome completo', { exact: true }).fill('Pessoa com formulário aberto');
  await page.getByLabel('Email', { exact: true }).fill(`pessoa.${Date.now()}@e2e.kianda.test`);
  await page.getByLabel('Telefone', { exact: true }).fill('923000222');
  await page.getByLabel('Ligação para o CV (em alternativa)', { exact: true }).fill('https://example.com/cv.pdf');
  await page.getByLabel('Autorizo o tratamento dos meus dados para este processo de recrutamento.', { exact: true }).check();
  expect((await apiAs(owner.token, 'PATCH', `/v1/openings/${created.body.id}`, { status: 'on_hold' })).status).toBe(200);
  await page.getByRole('button', { name: 'Enviar candidatura', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Formulário de candidatura', exact: true }).getByRole('alert')).toContainText('já não está a receber candidaturas');
  await page.reload(); await expect(page.getByRole('heading', { name: 'Vaga indisponível', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Ver outras vagas', exact: true })).toHaveAttribute('href', `/carreiras/${owner.id}`);
  expect((await apiAs(owner.token, 'PATCH', `/v1/openings/${created.body.id}`, { status: 'open', isPublic: true })).status).toBe(200);
  await page.goto(path); await expect(page.getByRole('heading', { name: 'Vaga temporária', exact: true })).toBeVisible();
  expect((await apiAs(owner.token, 'PATCH', `/v1/openings/${created.body.id}`, { status: 'closed' })).status).toBe(200);
  await page.reload(); await expect(page.getByRole('heading', { name: 'Vaga indisponível', exact: true })).toBeVisible();
  expect((await apiAs(owner.token, 'GET', `/v1/openings/${created.body.id}`)).body.candidates).toHaveLength(0);
});

test('falha de rede conserva contactos e CV e permite repetir a candidatura', async ({ page }) => {
  const owner = await registerCompany();
  const o = await apiAs(owner.token, 'POST', '/v1/openings', { title: 'Vaga com repetição segura', status: 'open', isPublic: true }); expect(o.status).toBe(201);
  await page.goto(o.body.publicPath);
  await page.getByLabel('Nome completo', { exact: true }).fill('Bento Recuperação');
  await page.getByLabel('Email', { exact: true }).fill(`bento.${Date.now()}@e2e.kianda.test`);
  await page.getByLabel('Telefone', { exact: true }).fill('923000333');
  await page.getByLabel('Currículo (CV)', { exact: true }).setInputFiles({ name: 'curriculo-bento.pdf', mimeType: 'application/pdf', buffer: cv() });
  await page.getByLabel('Autorizo o tratamento dos meus dados para este processo de recrutamento.', { exact: true }).check();
  await page.route('**/api/v1/public/careers/**/apply', route => route.abort('failed'), { times: 1 });
  await page.getByRole('button', { name: 'Enviar candidatura', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Formulário de candidatura', exact: true }).getByRole('alert')).toContainText('Verifique a ligação');
  await expect(page.getByLabel('Nome completo', { exact: true })).toHaveValue('Bento Recuperação');
  await expect(page.getByRole('button', { name: 'Remover CV', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Enviar candidatura', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Candidatura recebida');
  expect((await apiAs(owner.token, 'GET', `/v1/openings/${o.body.id}`)).body.candidates).toHaveLength(1);
});
