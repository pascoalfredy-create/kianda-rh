/** Smoke público depois de publicar: sem cookies, credenciais ou dados de empresas. */
import assert from 'node:assert/strict';
const origin = process.argv[2];
assert(origin?.startsWith('https://'), 'Indique o endereço HTTPS principal');
const get = (path) => fetch(new URL(path, origin), { redirect: 'manual', signal: AbortSignal.timeout(30000) });
const [home, robots, sitemap, manifest, modeling, login, prototype, registration] = await Promise.all(['/', '/robots.txt', '/sitemap.xml', '/manifest.webmanifest', '/modelagem', '/login', '/prototipo-inicio', '/registo?modulo=modeling&plano=corporate&ciclo=annual'].map(get));
assert.equal(home.status, 200, 'A apresentação pública tem de responder 200 sem sessão');
const html = await home.text();
assert.match(html, /<h1>Cuide da sua equipa\.<br\s*\/?><em>Prepare o próximo investimento\.<\/em><\/h1>/);
assert.match(html, /Recursos Humanos e Modelagem Financeira para empresas em Angola/);
assert(!html.includes('PROTÓTIPO PARA REVISÃO'), 'A página principal apresenta o desenho aprovado, sem avisos de protótipo');
assert.match(html, /aria-label="Kianda — página inicial"/);
assert.match(html, /Ver planos/); assert.match(html, /<dialog/);
assert(!/<dialog[^>]*\sopen(?:[\s=>])/.test(html), 'Os planos começam recolhidos');
assert.match(html, /<meta name="robots" content="index, follow"/);
assert.equal(new URL(/<link rel="canonical" href="([^"]+)"/.exec(html)?.[1]).href, 'https://kianda.yelaperformance.com/');
assert.match(html, /application\/ld\+json/);
for (const section of ['explorar', 'panel-modulos', 'panel-comecar', 'panel-duvidas']) assert(html.includes(`id="${section}"`), `Conteúdo público em falta: ${section}`);
assert.equal(robots.status, 200); assert.match(await robots.text(), /Sitemap: https:\/\/kianda\.yelaperformance\.com\/sitemap.xml/);
assert.equal(sitemap.status, 200);
const xml = await sitemap.text();
assert.match(xml, /<loc>https:\/\/kianda\.yelaperformance\.com<\/loc>/);
assert.equal((xml.match(/<loc>/g) || []).length, 1, 'O índice só contém a apresentação pública');
assert.equal(manifest.status, 200);
assert((await manifest.json()).shortcuts.some(shortcut => shortcut.url === '/modelagem'));
assert.equal(modeling.status, 303, 'O Integra continua protegido por sessão');
assert.equal(new URL(modeling.headers.get('location'), origin).pathname, '/login');
assert.equal(login.status, 200); assert.match(await login.text(), /<meta name="robots" content="noindex, nofollow"/);
assert.equal(prototype.status, 200);
const proposed = await prototype.text();
assert.match(proposed, /PROTÓTIPO PARA REVISÃO/); assert.match(proposed, /<meta name="robots" content="noindex, nofollow"/);
assert.match(proposed, /Ver planos/); assert.match(proposed, /role="tabpanel"/); assert.match(proposed, /<dialog/);
assert(!xml.includes('prototipo-inicio'), 'O protótipo de revisão não entra no sitemap');
assert.equal(registration.status, 200);
const form = await registration.text();
assert.match(form, /<option value="corporate" selected=""/);
assert.match(form, /<option value="annual" selected=""/);
assert(!form.includes('Pagamento RH'), 'Escolher Integra conserva o módulo escolhido no registo');
console.log('Público OK: página principal aprovada 200, planos recolhidos e escolha preservada no registo, metadados, robots, sitemap e Integra no manifest; login e projectos protegidos; prévia separada e sem indexação.');
